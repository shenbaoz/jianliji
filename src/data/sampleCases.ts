export function filterSampleCases(
  cases: SampleResumeCase[],
  category: string,
  audience: "全部" | "应届/实习" | "社招"
) {
  return cases.filter((item) => {
    const matchesCategory = category === "全部" || classifyRole(item.targetRole, item.jobDescription) === category;
    const isGraduate = item.candidateType === "graduate" || /应届|实习|在校/.test(item.resumeText);
    const matchesAudience = audience === "全部" || (audience === "应届/实习" ? isGraduate : !isGraduate);
    return matchesCategory && matchesAudience;
  });
}
